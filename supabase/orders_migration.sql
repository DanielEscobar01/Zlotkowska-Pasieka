-- Add persistent customer orders, immutable item price snapshots, and admin-only order access.
-- Run this migration in the Supabase SQL Editor after schema.sql has been applied.

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  customer_name text not null check (char_length(btrim(customer_name)) between 1 and 120),
  customer_phone text not null check (
    char_length(customer_phone) between 6 and 30
    and customer_phone ~ '^[+0-9() .-]+$'
    and customer_phone ~ '[0-9]'
  ),
  delivery_method text not null check (delivery_method in ('pickup', 'shipping')),
  street text,
  apartment text,
  postal_code text,
  city text,
  notes text not null default '',
  customer_language text not null default 'pl' check (customer_language in ('pl', 'en', 'uk', 'es')),
  items_subtotal numeric(10, 2) not null check (items_subtotal >= 0),
  delivered boolean not null default false,
  delivered_at timestamptz,
  constraint orders_shipping_address_required check (
    delivery_method <> 'shipping'
    or (nullif(btrim(street), '') is not null
      and nullif(btrim(postal_code), '') is not null
      and nullif(btrim(city), '') is not null)
  ),
  constraint orders_delivery_timestamp_consistent check (
    delivered = (delivered_at is not null)
  )
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id integer not null,
  product_name text not null,
  product_weight text not null,
  quantity integer not null check (quantity > 0),
  gift_box_count integer not null default 0 check (gift_box_count >= 0 and gift_box_count <= quantity),
  regular_unit_price numeric(10, 2) not null check (regular_unit_price >= 0),
  sale_unit_price numeric(10, 2) not null check (sale_unit_price >= 0),
  promo_applied boolean not null default false,
  gift_box_unit_price numeric(10, 2) not null default 5 check (gift_box_unit_price >= 0),
  line_total numeric(10, 2) not null check (line_total >= 0)
);

create index if not exists orders_created_at_desc_idx on public.orders (created_at desc);
create index if not exists order_items_order_id_idx on public.order_items (order_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

revoke all on public.orders, public.order_items from anon, authenticated;
grant select on public.orders, public.order_items to authenticated;
grant update (delivered, delivered_at) on public.orders to authenticated;

drop policy if exists "Admins can read customer orders" on public.orders;
create policy "Admins can read customer orders"
  on public.orders for select to authenticated
  using (public.is_inventory_admin());

drop policy if exists "Admins can update order delivery status" on public.orders;
create policy "Admins can update order delivery status"
  on public.orders for update to authenticated
  using (public.is_inventory_admin())
  with check (public.is_inventory_admin());

drop policy if exists "Admins can read customer order items" on public.order_items;
create policy "Admins can read customer order items"
  on public.order_items for select to authenticated
  using (public.is_inventory_admin());

create or replace function public.create_customer_order(order_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  _order_id uuid;
  _customer_name text;
  _customer_phone text;
  _delivery_method text;
  _street text;
  _apartment text;
  _postal_code text;
  _city text;
  _notes text;
  _customer_language text;
  _item jsonb;
  _product_id integer;
  _quantity integer;
  _gift_box_count integer;
  _product_name text;
  _product_weight text;
  _regular_price numeric(10, 2);
  _sale_price numeric(10, 2);
  _promo_applied boolean;
  _line_total numeric(10, 2);
  _subtotal numeric(10, 2) := 0;
  _priced_items jsonb := '[]'::jsonb;
  _seen_product_ids integer[] := '{}'::integer[];
  _inventory public.product_inventory%rowtype;
begin
  if jsonb_typeof(order_data) is distinct from 'object' then
    raise exception 'invalid_order';
  end if;

  if jsonb_typeof(order_data->'items') is distinct from 'array' then
    raise exception 'invalid_order';
  end if;

  if jsonb_array_length(order_data->'items') < 1
    or jsonb_array_length(order_data->'items') > 30 then
    raise exception 'invalid_order';
  end if;

  _customer_name := nullif(btrim(order_data->>'customer_name'), '');
  _customer_phone := nullif(btrim(order_data->>'customer_phone'), '');
  _delivery_method := order_data->>'delivery_method';
  _street := nullif(btrim(order_data->>'street'), '');
  _apartment := nullif(btrim(order_data->>'apartment'), '');
  _postal_code := nullif(btrim(order_data->>'postal_code'), '');
  _city := nullif(btrim(order_data->>'city'), '');
  _notes := coalesce(order_data->>'notes', '');
  _customer_language := coalesce(order_data->>'customer_language', 'pl');

  if _customer_name is null or char_length(_customer_name) > 120
    or _customer_phone is null or char_length(_customer_phone) not between 6 and 30
    or _customer_phone !~ '^[+0-9() .-]+$' or _customer_phone !~ '[0-9]'
    or _delivery_method is null
    or _delivery_method not in ('pickup', 'shipping')
    or _customer_language not in ('pl', 'en', 'uk', 'es')
    or char_length(_notes) > 2000 then
    raise exception 'invalid_order_details';
  end if;

  if _delivery_method = 'shipping'
    and (_street is null or _postal_code is null or _city is null) then
    raise exception 'shipping_address_required';
  end if;

  for _item in select value from jsonb_array_elements(order_data->'items') as rows(value) loop
    if coalesce(_item->>'product_id', '') !~ '^[0-9]+$'
      or coalesce(_item->>'quantity', '') !~ '^[0-9]+$'
      or coalesce(_item->>'gift_box_count', '0') !~ '^[0-9]+$' then
      raise exception 'invalid_order_item';
    end if;

    _product_id := (_item->>'product_id')::integer;
    _quantity := (_item->>'quantity')::integer;
    _gift_box_count := coalesce((_item->>'gift_box_count')::integer, 0);

    if _product_id = any(_seen_product_ids) then
      raise exception 'duplicate_order_item';
    end if;
    _seen_product_ids := array_append(_seen_product_ids, _product_id);

    _product_name := nullif(btrim(_item->>'product_name'), '');
    _product_weight := nullif(btrim(_item->>'product_weight'), '');

    if _quantity < 1 or _gift_box_count < 0 or _gift_box_count > _quantity
      or _product_name is null or char_length(_product_name) > 160
      or _product_weight is null or char_length(_product_weight) > 40 then
      raise exception 'invalid_order_item';
    end if;

    if _product_id not in (1, 2, 3, 5, 6, 7, 8, 9) and _gift_box_count > 0 then
      raise exception 'gift_boxes_not_available';
    end if;

    select * into _inventory
    from public.product_inventory
    where product_id = _product_id
    for share;

    if not found then
      raise exception 'product_unavailable';
    end if;

    if _inventory.stock < _quantity then
      raise exception 'product_unavailable';
    end if;

    _regular_price := _inventory.price;
    _promo_applied := _inventory.promo_active
      and _inventory.promo_price is not null
      and _inventory.promo_price < _inventory.price;
    _sale_price := case when _promo_applied then _inventory.promo_price else _inventory.price end;
    _line_total := round(_sale_price * _quantity + 5 * _gift_box_count, 2);
    _subtotal := _subtotal + _line_total;
    _priced_items := _priced_items || jsonb_build_array(jsonb_build_object(
      'product_id', _product_id,
      'product_name', _product_name,
      'product_weight', _product_weight,
      'quantity', _quantity,
      'gift_box_count', _gift_box_count,
      'regular_unit_price', _regular_price,
      'sale_unit_price', _sale_price,
      'promo_applied', _promo_applied,
      'gift_box_unit_price', 5,
      'line_total', _line_total
    ));
  end loop;

  insert into public.orders (
    customer_name, customer_phone, delivery_method, street, apartment,
    postal_code, city, notes, customer_language, items_subtotal
  ) values (
    _customer_name, _customer_phone, _delivery_method, _street, _apartment,
    _postal_code, _city, _notes, _customer_language, _subtotal
  ) returning id into _order_id;

  insert into public.order_items (
    order_id, product_id, product_name, product_weight, quantity, gift_box_count,
    regular_unit_price, sale_unit_price, promo_applied, gift_box_unit_price, line_total
  )
  select
    _order_id,
    (item->>'product_id')::integer,
    item->>'product_name',
    item->>'product_weight',
    (item->>'quantity')::integer,
    (item->>'gift_box_count')::integer,
    (item->>'regular_unit_price')::numeric,
    (item->>'sale_unit_price')::numeric,
    (item->>'promo_applied')::boolean,
    (item->>'gift_box_unit_price')::numeric,
    (item->>'line_total')::numeric
  from jsonb_array_elements(_priced_items) as rows(item);

  return jsonb_build_object('id', _order_id, 'total', _subtotal, 'items', _priced_items);
end;
$$;

revoke all on function public.create_customer_order(jsonb) from public;
grant execute on function public.create_customer_order(jsonb) to anon, authenticated;

